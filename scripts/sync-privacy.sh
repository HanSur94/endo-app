#!/usr/bin/env bash
# Regenerates docs/privacy.md from the in-app policy string (the source of truth).
# Usage: scripts/sync-privacy.sh          rewrite docs/privacy.md
#        scripts/sync-privacy.sh --check  exit 1 if docs/privacy.md drifted (CI)
set -euo pipefail
cd "$(dirname "$0")/.."
python3 - "$@" <<'PY'
import re, sys, pathlib, textwrap

src = pathlib.Path('Sources/EndoApp/Content/PrivacyPolicyText.swift').read_text()
email = re.search(r'contactEmail\s*=\s*"([^"]+)"', src).group(1)
body = re.search(r'static let body: String = """\n(.*?)\n[ \t]*"""', src, re.S).group(1)
body = textwrap.dedent(body)

lines, out, buf = body.splitlines(), [], ''
for raw in lines:
    line = raw.rstrip()
    if buf:
        line, buf = buf + line.strip(), ''
    if line.endswith('\\'):
        buf = line[:-1].rstrip() + ' '
        continue
    out.append(line)
body = '\n'.join(out).replace('\\(contactEmail)', email)
# A short line that is not a sentence is a section lead-in — render it as a heading.
body = '\n'.join(
    ('### ' + line if len(line) <= 60 and not line.rstrip().endswith(('.', '!', '?', ':')) and line.strip() else line)
    for line in body.splitlines()
)
body = re.sub(r'\n{3,}', '\n\n', body).strip()

doc = (
    '# Privacy Policy\n\n'
    '_Canonical source: `Sources/EndoApp/Content/PrivacyPolicyText.swift`. '
    'Generated by `scripts/sync-privacy.sh` — do not edit by hand._\n\n'
    + body + '\n'
)
path = pathlib.Path('docs/privacy.md')
if '--check' in sys.argv:
    if not path.exists() or path.read_text() != doc:
        sys.exit('docs/privacy.md is out of sync with PrivacyPolicyText.swift — run scripts/sync-privacy.sh')
    print('docs/privacy.md in sync')
else:
    path.write_text(doc)
    print('wrote', path)
PY
